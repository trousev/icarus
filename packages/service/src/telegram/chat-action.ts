// «Действие» в Telegram: клиент показывает его вместо обычного статуса — «печатает…»,
// «отправляет файл…», «выбирает стикер…». Список закрыт: своих действий Bot API не
// принимает, поэтому фазы хода раскладываются по тому, что в списке ближе всего.
// Точное совпадение — редкость, остальное честная метафора (насколько честная —
// видно в таблице рядом с каждой строкой).

/** Действия Bot API: других Telegram не показывает. */
export type ChatAction =
  | 'typing'
  | 'upload_photo'
  | 'record_video'
  | 'upload_video'
  | 'record_voice'
  | 'upload_voice'
  | 'upload_document'
  | 'choose_sticker'
  | 'find_location'
  | 'record_video_note'
  | 'upload_video_note';

/** Действие живёт в клиенте около пяти секунд — повторяем чуть раньше. */
export const ACTION_INTERVAL_MS = 4500;

/**
 * Минимум между двумя действиями: смена фазы видна сразу, но частокол из
 * «печатает — файл — печатает» на быстрых тулах не стоит отправлять — Telegram
 * такой поток считает спамом и банит все запросы бота, а не только эти.
 */
export const ACTION_GAP_MS = 1000;

/**
 * Сколько ход может показывать стикер, прежде чем вернуться к честному «печатает»:
 * мысль без слов — это «выбирает стикер», но затянувшаяся шутка читается как залипший бот.
 */
export const STICKER_LIE_MS = 15_000;

/** Модель думает: наружу ничего не ушло, и точнее стикера в списке ничего нет. */
export const THINKING_ACTION: ChatAction = 'choose_sticker';

/** Чем показывать тул, пока он не ответил. */
export function actionForTool(toolName: string): ChatAction {
  switch (toolName) {
    // Файлы: чтение, правка, запись — в списке есть ровно одно «про файлы».
    case 'read':
    case 'write':
    case 'edit':
      return 'upload_document';
    // Субагенты уходят искать по сторонам: ближе всего «отправляет геопозицию».
    case 'subagent':
      return 'find_location';
    // Поиск по файлам и команды: действия нет, и врать громче нечем.
    default:
      return 'typing';
  }
}
