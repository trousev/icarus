#!/usr/bin/env bash
# Справка по размеру промпта. Жёсткого лимита больше нет: во время прокачки он держал
# промпт в узде, сейчас это ориентир (1–2 страницы A4 ≈ 90 непустых строк).
set -euo pipefail
cd "$(dirname "$0")"
file="${1:-persona.md}"
lines=$(grep -c '[^[:space:]]' "$file" || true)
chars=$(wc -m < "$file")
echo "$file: непустых строк $lines, символов $chars"
if [ "$lines" -gt 90 ]; then
  echo "ориентир 90 строк превышен — не ошибка, но проверь, что каждая новая строка работает"
fi
